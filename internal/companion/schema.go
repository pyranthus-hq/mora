// NewReceipt returns a receipt with its envelope filled in.
func NewReceipt() Receipt { return Receipt{Header: newHeader(SchemaReceipt)} }

func (r *Receipt) SchemaName() string { return SchemaReceipt }
func (r *Receipt) ByteLimit() int     { return MaxProjectionBytes }

func (r *Receipt) Validate() error {
	if err := r.validate(SchemaReceipt); err != nil {
		return err
	}
	if err := validateID("receipt_id", PrefixReceipt, r.ReceiptID); err != nil {
		return err
	}
	if err := validateID("request_id", PrefixRequest, r.RequestID); err != nil {
		return err
	}
	if err := validateIdempotencyKey("idempotency_key", r.IdempotencyKey); err != nil {
		return err
	}
	if err := validateID("device_id", PrefixDevice, r.DeviceID); err != nil {
		return err
	}
	if err := inVocabulary("receipt_state", string(r.State), "state"); err != nil {
		return err
	}
	if err := inVocabulary("write_policy", string(r.Policy), "policy"); err != nil {
		return err
	}
	if err := validateFingerprint("payload_fingerprint", r.PayloadFingerprint); err != nil {
		return err
	}
	if err := validateTimestamp("received_at", r.ReceivedAt); err != nil {
		return err
	}
	if err := validateOptionalTimestamp("settled_at", r.SettledAt); err != nil {
		return err
	}
	if err := validateOptionalID("memory_id", PrefixMemory, r.MemoryID); err != nil {
		return err
	}
	if r.Reason != "" {
		if err := inVocabulary("reject_reason", string(r.Reason), "reason"); err != nil {
			return err
		}
	}
	switch r.State {
	case ReceiptApplied:
		// The whole point of the receipt: applied is a claim that the vault
		// holds the memory, so it cannot be made without naming it.
		if r.MemoryID == "" {
			return errf(CodeInvalidState, "memory_id", "an applied receipt names the memory it created")
		}
		if r.SettledAt == "" {
			return errf(CodeInvalidState, "settled_at", "an applied receipt is settled")
		}
		if r.Reason != "" {
			return errf(CodeInvalidState, "reason", "an applied receipt has no rejection reason")
		}
	case ReceiptRejected:
		if r.Reason == "" {
			return errf(CodeMissingField, "reason", "a rejected receipt names its reason")
		}
		if r.MemoryID != "" {
			return errf(CodeInvalidState, "memory_id", "a rejected receipt created no memory")
		}
		if r.SettledAt == "" {
			return errf(CodeInvalidState, "settled_at", "a rejected receipt is settled")
		}
	case ReceiptAccepted:
		if r.MemoryID != "" {
			return errf(CodeInvalidState, "memory_id", "an accepted receipt has not published a memory yet")
		}
		if r.Reason != "" {
			return errf(CodeInvalidState, "reason", "an accepted receipt has no rejection reason")
		}
	}
	if err := validatePolicyOutcome(r.State, r.Reason, r.Policy); err != nil {
		return err
	}
	if r.Operation == nil {
		return nil
	}
	op := r.Operation
	if op.RequestID != r.RequestID {
		return errf(CodeInvalidState, "operation.request_id", "operation belongs to a different request")
	}
	if err := validateID("operation.request_id", PrefixRequest, op.RequestID); err != nil {
		return err
	}
	if err := inVocabulary("lane", string(op.Lane), "operation.lane"); err != nil {
		return err
	}
	if err := inVocabulary("kind", string(op.Kind), "operation.kind"); err != nil {
		return err
	}
	if err := inVocabulary("operation_state", string(op.State), "operation.state"); err != nil {
		return err
	}
	if err := validateTimestamp("operation.updated_at", op.UpdatedAt); err != nil {
		return err
	}
	if op.Attempts < 0 {
		return errf(CodeInvalidValue, "operation.attempts", "count cannot be negative")
	}
	return nil
}

// validatePolicyOutcome binds a receipt's state to the write policy that
// produced it, so a receipt cannot describe an outcome the policy could not
// have reached.
//
// The binding applies to the policy-determined outcomes — the ones where the
// policy alone decided what happened, which is when the receipt carries no
// reason or carries ReasonPolicy:
//
//	readonly -> rejected    propose -> accepted    open -> applied
//
// Every other rejection reason (unknown_device, too_large, idempotency_conflict
// and the rest) can occur under any policy, and those receipts are required to
// be rejected and are not bound further. Binding them to a policy as well would
// make an oversize capture unrepresentable under `open`, which is a real case
// N21 has to return.
func validatePolicyOutcome(state ReceiptState, reason RejectReason, policy WritePolicy) error {
	if reason != "" && reason != ReasonPolicy {
		if state != ReceiptRejected {
			return errf(CodeInvalidState, "state", "reason %q can only produce a rejected receipt", reason)
		}
		return nil
	}
	want := map[WritePolicy]ReceiptState{
		PolicyReadonly: ReceiptRejected,
		PolicyPropose:  ReceiptAccepted,
		PolicyOpen:     ReceiptApplied,
	}[policy]
	if state != want {
		return errf(CodeInvalidState, "state", "the %s policy produces a %s receipt, not %s", policy, want, state)
	}
	return nil
}

