// Byte and count bounds. Every bound is enforced by Validate or by Unmarshal,
// never left to the caller: an unbounded field is how a phone turns a projection
// into a denial of service and how a capture turns a log line into a leak.
const (
	// MaxCaptureBytes bounds a whole capture request. The text inside it is
	// bounded separately by MaxCaptureTextBytes.
	MaxCaptureBytes     = 24 << 10
	MaxCaptureTextBytes = 16 << 10
	// MaxRequestBytes bounds any other inbound request body.
	MaxRequestBytes = 64 << 10
	// MaxProjectionBytes bounds any outbound projection (Today, context,
	// health, receipt, device, pairing).
	MaxProjectionBytes = 4 << 20
	// MaxOperationBytes bounds the async operation envelope. It is small
	// because the envelope carries no user text — only a reference to it.
	MaxOperationBytes = 4 << 10

	MaxIDBytes              = 64
	MaxIdempotencyKeyBytes  = 128
	MaxLabelBytes           = 64
	MaxScopeBytes           = 128
	MaxQueryBytes           = 1 << 10
	MaxTitleBytes           = 200
	MaxBodyBytes            = 2 << 10
	MaxSnippetBytes         = 512
	MaxSourceKeyBytes       = 64
	MaxPublicKeyBytes       = 128
	MaxSynthesisPromptBytes = 8 << 10
	MaxGapBytes             = 200
	MaxDeepLinkBytes        = 512

	MaxTodayItems       = 3
	MaxEvidencePerItem  = 5
	MaxContextEvidence  = 32
	MaxCitations        = 32
	MaxGaps             = 16
	MaxFreshnessSources = 32
)

