// Package companion holds the wire contract between a paired phone and the
// Mora kernel: the JSON schemas for device, pairing, Today, context, capture,
// receipt and health, plus the async operation envelope (envelope.go).
//
// The package is deliberately a leaf. It contains types, bounds, a stable enum
// vocabulary, strict decoding and validation — no I/O, no clock, no vault, no
// HTTP. It imports only the standard library and must never import
// internal/mora, so the contract can be compiled into fixtures, tests and other
// packages without dragging the kernel behind it. TestPackageIsALeaf enforces
// that.
//
// # The envelope keys
//
// Every payload carries "schema" and "schema_version" merged into the object,
// matching the machine contract in docs/architecture/22-cli-contracts.md.
// Adding a field is MINOR; removing, renaming or retyping one requires a
// SchemaVersion bump and a new golden directory.
//
// # Strict inbound, tolerant outbound
//
// The kernel decodes everything a device sends with DisallowUnknownFields and
// rejects an unknown field, an unknown enum value, an oversize body or a
// malformed timestamp. A device decoding a kernel projection must do the
// opposite: ignore fields it does not know, because new ones will appear
// without a version bump. Both halves are proved by tests in fixtures_test.go.
//
// # Timestamps
//
// Every timestamp is RFC3339, UTC, second precision, "Z" suffix, no fractional
// part. That is narrower than RFC3339 on purpose: it is what Swift's
// ISO8601DateFormatter parses with its default options, so the Go and Swift
// decoders agree on the committed goldens without per-field date strategies.
package companion

