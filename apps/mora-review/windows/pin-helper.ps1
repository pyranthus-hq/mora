param(
    [Parameter(Mandatory = $true)][string]$Helper,
    [Parameter(Mandatory = $true)][string]$GeneratedGo
)

# Run only after the final optional Authenticode signature. The Go release then
# owns this exact digest; developer builds deliberately retain an empty digest.
$ErrorActionPreference = 'Stop'
if (!(Test-Path -LiteralPath $Helper -PathType Leaf)) { throw "Missing helper: $Helper" }
$hash = (Get-FileHash -LiteralPath $Helper -Algorithm SHA256).Hash.ToLowerInvariant()
if ($hash -notmatch '^[0-9a-f]{64}$') { throw 'Could not calculate the helper SHA-256.' }
$contents = @(
'//go:build windows',
'',
'package mora',
'',
'// Code generated by apps/mora-review/windows/pin-helper.ps1 after final PE signing; DO NOT EDIT.',
('const nativeOwnerWindowsHelperSHA256 = "{0}"' -f $hash),
'const nativeOwnerWindowsHelperFilename = "MoraReview.exe"',
 '') -join "`n"
[System.IO.File]::WriteAllText($GeneratedGo, $contents, [System.Text.UTF8Encoding]::new($false))
Write-Output "Pinned MoraReview.exe SHA-256: $hash"
