// VocabularyFamilies returns every published enum family, sorted.
func VocabularyFamilies() []string {
	out := make([]string, 0, len(vocabulary))
	for family := range vocabulary {
		out = append(out, family)
	}
	sort.Strings(out)
	return out
}

// VocabularyFor returns the published values of one enum family. The returned
// slice is a copy: the contract's vocabulary is not writable from outside this
// package.
func VocabularyFor(family string) []string {
	out := make([]string, len(vocabulary[family]))
	copy(out, vocabulary[family])
	return out
}

func inVocabulary(family, value, field string) error {
	for _, v := range vocabulary[family] {
		if v == value {
			return nil
		}
	}
	if value == "" {
		return errf(CodeMissingField, field, "%s is required", family)
	}
	return errf(CodeInvalidEnum, field, "not a published %s value", family)
}

// ---------------------------------------------------------------------------
// Header
// ---------------------------------------------------------------------------

// Header is the two-key envelope every payload merges in. It is embedded, so it
// marshals flat and first.
type Header struct {
	Schema        string `json:"schema"`
	SchemaVersion int    `json:"schema_version"`
}

func newHeader(name string) Header {
	return Header{Schema: name, SchemaVersion: SchemaVersion}
}

func (h Header) validate(name string) error {
	if h.Schema != name {
		return errf(CodeSchemaMismatch, "schema", "want %s", name)
	}
	if h.SchemaVersion != SchemaVersion {
		return errf(CodeSchemaMismatch, "schema_version", "want %d", SchemaVersion)
	}
	return nil
}

// ---------------------------------------------------------------------------
// Scalar validation
// ---------------------------------------------------------------------------

// validateTimestamp enforces RFC3339, UTC, second precision. See the package
// doc for why the format is narrower than RFC3339 itself.
func validateTimestamp(field, s string) error {
	if s == "" {
		return errf(CodeMissingField, field, "timestamp is required")
	}
	if !strings.HasSuffix(s, "Z") {
		return errf(CodeInvalidValue, field, "timestamp must be UTC and end in Z")
	}
	t, err := time.Parse(time.RFC3339, s)
	if err != nil {
		return errf(CodeInvalidValue, field, "timestamp is not RFC3339")
	}
	if t.UTC().Format(time.RFC3339) != s {
		return errf(CodeInvalidValue, field, "timestamp must have second precision and no fractional part")
	}
	return nil
}

func validateOptionalTimestamp(field, s string) error {
	if s == "" {
		return nil
	}
	return validateTimestamp(field, s)
}

// opaqueRunes reports whether s is limited to the opaque-token character set.
// Restricting it is what keeps a device from smuggling prose through an
// identifier into the content-free operation envelope.
func opaqueRunes(s string) bool {
	for _, r := range s {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9':
		case r == '_' || r == '-' || r == '.' || r == ':':
		default:
			return false
		}
	}
	return true
}

func validateID(field, prefix, s string) error {
	if s == "" {
		return errf(CodeMissingField, field, "identifier is required")
	}
	if len(s) > MaxIDBytes {
		return errf(CodeTooLarge, field, "identifier exceeds %d bytes", MaxIDBytes)
	}
	if !strings.HasPrefix(s, prefix) || len(s) == len(prefix) {
		return errf(CodeInvalidValue, field, "identifier must start with %q and carry an opaque suffix", prefix)
	}
	if !opaqueRunes(s) {
		return errf(CodeInvalidValue, field, "identifier carries characters outside [A-Za-z0-9_.:-]")
	}
	return nil
}

func validateOptionalID(field, prefix, s string) error {
	if s == "" {
		return nil
	}
	return validateID(field, prefix, s)
}

func validateText(field, s string, max int, required bool) error {
	if s == "" {
		if required {
			return errf(CodeMissingField, field, "field is required")
		}
		return nil
	}
	if len(s) > max {
		return errf(CodeTooLarge, field, "exceeds %d bytes", max)
	}
	return nil
}

func validateCount(field string, n, max int) error {
	if n > max {
		return errf(CodeTooManyItems, field, "at most %d entries", max)
	}
	return nil
}

// validateFingerprint accepts only "sha256:" plus 64 lowercase hex digits.
func validateFingerprint(field, s string) error {
	const want = "sha256:"
	if s == "" {
		return errf(CodeMissingField, field, "fingerprint is required")
	}
	if !strings.HasPrefix(s, want) || len(s) != len(want)+64 {
		return errf(CodeInvalidValue, field, "fingerprint must be sha256:<64 hex>")
	}
	for _, r := range s[len(want):] {
		if r >= '0' && r <= '9' || r >= 'a' && r <= 'f' {
			continue
		}
		return errf(CodeInvalidValue, field, "fingerprint digest must be lowercase hex")
	}
	return nil
}

func validateOptionalFingerprint(field, s string) error {
	if s == "" {
		return nil
	}
	return validateFingerprint(field, s)
}

// validateScope accepts "personal" or "project:<name>". A device may not invent
// any other scope, and it may never name a source.
func validateScope(field, s string) error {
	if s == "" {
		return errf(CodeMissingField, field, "scope is required")
	}
	if len(s) > MaxScopeBytes {
		return errf(CodeTooLarge, field, "exceeds %d bytes", MaxScopeBytes)
	}
	if s == "personal" {
		return nil
	}
	name, ok := strings.CutPrefix(s, "project:")
	if !ok || name == "" || !opaqueRunes(name) {
		return errf(CodeInvalidValue, field, `scope must be "personal" or "project:<name>"`)
	}
	return nil
}

func validateIdempotencyKey(field, s string) error {
	if s == "" {
		return errf(CodeMissingField, field, "idempotency key is required")
	}
	if len(s) > MaxIdempotencyKeyBytes {
		return errf(CodeTooLarge, field, "exceeds %d bytes", MaxIdempotencyKeyBytes)
	}
	if !opaqueRunes(s) {
		return errf(CodeInvalidValue, field, "idempotency key carries characters outside [A-Za-z0-9_.:-]")
	}
	return nil
}

// ---------------------------------------------------------------------------
// Decoding
// ---------------------------------------------------------------------------

// Payload is implemented by every schema in this package.
type Payload interface {
	// SchemaName is the published name the payload must carry.
	SchemaName() string
	// ByteLimit is the largest encoded form the kernel will accept.
	ByteLimit() int
	// Validate enforces every bound, enum and cross-field rule.
	Validate() error
}

// Unmarshal decodes data into v with unknown fields rejected, enforces v's byte
// limit, and validates. It is the only decode path the kernel uses on anything
// a device sent.
func Unmarshal(data []byte, v Payload) error {
	if limit := v.ByteLimit(); limit > 0 && len(data) > limit {
		return errf(CodeTooLarge, "", "payload is %d bytes, limit is %d", len(data), limit)
	}
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	if err := dec.Decode(v); err != nil {
		if strings.Contains(err.Error(), "unknown field") {
			return errf(CodeUnknownField, "", "%s", err.Error())
		}
		return errf(CodeMalformed, "", "%s", err.Error())
	}
	if dec.More() {
		return errf(CodeMalformed, "", "trailing data after the JSON document")
	}
	return v.Validate()
}

// Marshal encodes a validated payload in the golden form: two-space indent and
// a trailing newline, so a committed fixture and a live response are the same
// bytes.
func Marshal(v Payload) ([]byte, error) {
	if err := v.Validate(); err != nil {
		return nil, err
	}
	b, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		return nil, err
	}
	b = append(b, '\n')
	// The bound is enforced on the way out as well as on the way in. Checking
	// it only on decode would leave a producer free to emit an operation
	// envelope past 4 KiB or a projection past 4 MiB, and the peer that
	// rejected it would be the only one to find out.
	if limit := v.ByteLimit(); limit > 0 && len(b) > limit {
		return nil, errf(CodeTooLarge, "", "encoded payload is %d bytes, limit is %d", len(b), limit)
	}
	return b, nil
}

// Fingerprint returns the payload fingerprint for a capture's text. It is the
// published derivation: SHA-256 over the exact UTF-8 bytes the device sent,
// rendered lowercase with a "sha256:" prefix. A device computes it, the kernel
// recomputes it, and a mismatch on a repeated idempotency key is
// ReasonIdempotencyConflict.
func Fingerprint(text string) string {
	sum := sha256.Sum256([]byte(text))
	return "sha256:" + hex.EncodeToString(sum[:])
}

