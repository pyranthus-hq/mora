// Error is the single error type this package returns. Field names the JSON
// path where that is known, so a rejection receipt can say what was wrong
// without echoing the value back into a log.
type Error struct {
	Code    string
	Field   string
	Message string
}

func (e *Error) Error() string {
	if e.Field == "" {
		return e.Code + ": " + e.Message
	}
	return e.Code + " at " + e.Field + ": " + e.Message
}

func errf(code, field, format string, args ...any) *Error {
	return &Error{Code: code, Field: field, Message: fmt.Sprintf(format, args...)}
}

